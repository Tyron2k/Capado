import { test, expect } from '@playwright/test'
import { execFileSync } from 'node:child_process'

test('collapsed desktop navigation remains usable on mobile, including keyboard dismissal', async ({ page }) => {
  execFileSync('uv', ['--directory', '../backend', 'run', '--frozen', '--no-dev', 'python', '-m', 'tests.e2e_server', 'reset'])
  await page.addInitScript(() => localStorage.setItem('user-preferences', JSON.stringify({ locale: 'en', colorScheme: 'light', navCollapsed: true })))
  await page.setViewportSize({ width: 1280, height: 800 })
  await page.goto('/login')
  await page.getByLabel(/^Email/).fill('editor@example.test')
  await page.getByLabel(/^Password/).fill('browser-tests-only')
  await page.getByRole('button', { name: 'Sign In', exact: true }).click()
  await expect(page).toHaveURL('/')
  const nav = page.getByRole('navigation')
  const projects = nav.getByRole('link', { name: 'Projects', exact: true })
  await projects.focus()
  await page.keyboard.press('Shift+Tab')
  await page.keyboard.press('Tab')
  await expect(page.getByRole('tooltip', { name: 'Projects', exact: true })).toBeVisible()
  // Roles and names survive both presentations; admin-only pages stay hidden.
  await expect(nav.getByRole('link', { name: 'Settings', exact: true })).toHaveCount(0)
  await page.setViewportSize({ width: 390, height: 844 })
  const expand = page.getByRole('button', { name: 'Expand navigation', exact: true })
  await expand.click()
  await expect(nav).toBeVisible()
  await expect(projects.getByText('Projects', { exact: true })).toBeVisible()
  await page.keyboard.press('Escape')
  await expect(expand).toHaveAttribute('aria-expanded', 'false')
  await expand.click()
  await projects.click()
  await expect(page).toHaveURL('/projects')
  await expect(expand).toHaveAttribute('aria-expanded', 'false')
  await expect(page.getByRole('heading', { name: 'Projects', exact: true })).toBeVisible()
  await expect.poll(() => page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
})
