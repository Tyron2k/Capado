"""Generate and load revisions without the retired SQLModel dependency."""

import asyncio
import shutil
import sys
from pathlib import Path

import pytest
from alembic.config import Config
from alembic.script import ScriptDirectory

from alembic import command
from tests.test_utc_migration_postgres import legacy_database, migrate

ROOT = Path(__file__).resolve().parents[1]


@pytest.fixture
def migration_config(tmp_path, monkeypatch):
    """Use the actual template and history, but write only to a temporary copy."""
    scripts = tmp_path / "alembic"
    shutil.copytree(
        ROOT / "alembic", scripts, ignore=shutil.ignore_patterns("__pycache__")
    )
    config = Config(str(ROOT / "alembic.ini"))
    config.set_main_option("script_location", str(scripts))
    # Also catch the regression in an environment that happens to retain SQLModel.
    monkeypatch.setitem(sys.modules, "sqlmodel", None)
    return config


def test_generated_revision_loads_without_sqlmodel(migration_config):
    previous_head = ScriptDirectory.from_config(migration_config).get_current_head()
    revision = command.revision(
        migration_config, message="Template regression", rev_id="template_test"
    )
    assert revision.down_revision == previous_head
    assert (
        ScriptDirectory.from_config(migration_config).get_current_head()
        == revision.revision
    )
    revision.module.upgrade()
    revision.module.downgrade()


async def test_autogenerated_revision_matches_native_postgres_models(
    migration_config, legacy_database, monkeypatch
):
    url, _engine = legacy_database
    result = await migrate(url, "head")
    assert result.returncode == 0, result.stderr
    monkeypatch.setenv("DATABASE_URL", url)
    previous_head = ScriptDirectory.from_config(migration_config).get_current_head()
    revision = await asyncio.to_thread(
        command.revision,
        migration_config,
        message="Native metadata regression",
        rev_id="autogen_test",
        autogenerate=True,
    )
    assert revision.down_revision == previous_head
    assert (
        ScriptDirectory.from_config(migration_config).get_current_head()
        == revision.revision
    )
    # The migrated schema already matches ORMModel.metadata. No invented schema
    # change is needed to exercise the real env.py/autogenerate/template path.
    revision.module.upgrade()
    revision.module.downgrade()
